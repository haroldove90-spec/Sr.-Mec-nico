/**
 * Busca especificaciones por texto flexible (marca, modelo, año)
 */
export function findVehicleSpec(query: string): VehicleSpec | null {
  const q = query.toLowerCase().trim();
  if (!q) return null;

  // 1. Coincidencia directa por marca y modelo
  for (const spec of VEHICLE_SPECS_DATABASE) {
    const make = spec.make.toLowerCase();
    const model = spec.model.toLowerCase();
    if (q.includes(make) && q.includes(model)) {
      return spec;
    }
  }

  // 2. Coincidencia por modelo únicamente (ej. "Versa", "Jetta", "Aveo", "Corolla", "Civic", "Onix")
  for (const spec of VEHICLE_SPECS_DATABASE) {
    const model = spec.model.toLowerCase();
    if (q.includes(model)) {
      return spec;
    }
  }

  return null;
}
